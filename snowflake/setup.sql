
-- Mortgage Underwriting Pipeline
-- Create database, schemas, warehouse, and RAW tables.

CREATE DATABASE IF NOT EXISTS MORTGAGE_DB;

CREATE SCHEMA IF NOT EXISTS MORTGAGE_DB.RAW;
CREATE SCHEMA IF NOT EXISTS MORTGAGE_DB.SILVER;
CREATE SCHEMA IF NOT EXISTS MORTGAGE_DB.GOLD;

CREATE WAREHOUSE IF NOT EXISTS MORTGAGE_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

-- Store each JSON application as a VARIANT payload.
CREATE TABLE IF NOT EXISTS MORTGAGE_DB.RAW.MORTGAGE_APPLICATIONS_RAW (
    PAYLOAD VARIANT,
    SOURCE_FILE VARCHAR,
    LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Store credit bureau CSV records.
CREATE TABLE IF NOT EXISTS MORTGAGE_DB.RAW.CREDIT_BUREAU_RAW (
    APPLICANT_ID NUMBER,
    SSN VARCHAR(20),
    CREDIT_SCORE NUMBER,
    MONTHLY_DEBT NUMBER(12,2),
    SOURCE_FILE VARCHAR,
    LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- File formats for future source loading.
CREATE FILE FORMAT IF NOT EXISTS MORTGAGE_DB.RAW.MORTGAGE_JSON_FORMAT
    TYPE = JSON
    STRIP_OUTER_ARRAY = TRUE;

CREATE FILE FORMAT IF NOT EXISTS MORTGAGE_DB.RAW.CREDIT_CSV_FORMAT
    TYPE = CSV
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"';
