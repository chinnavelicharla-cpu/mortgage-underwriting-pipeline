
-- Join mortgage applications with credit bureau records.
-- FULL OUTER JOIN preserves records missing from either source.

SELECT
    COALESCE(m.APPLICANT_ID, c.APPLICANT_ID) AS APPLICANT_ID,
    m.APPLICANT_NAME,
    m.LOAN_AMOUNT,
    m.PROPERTY_VALUE,
    m.MONTHLY_INCOME,
    c.SSN,
    c.CREDIT_SCORE,
    c.MONTHLY_DEBT,
    m.SOURCE_FILE AS APPLICATION_SOURCE_FILE,
    c.SOURCE_FILE AS CREDIT_SOURCE_FILE,
    m.LOADED_AT AS APPLICATION_LOADED_AT,
    c.LOADED_AT AS CREDIT_LOADED_AT,

    CASE
        WHEN m.APPLICANT_ID IS NULL THEN 'MISSING_APPLICATION'
        WHEN c.APPLICANT_ID IS NULL THEN 'MISSING_CREDIT_RECORD'
        WHEN m.LOAN_AMOUNT IS NULL OR m.LOAN_AMOUNT <= 0
            THEN 'INVALID_LOAN_AMOUNT'
        WHEN m.PROPERTY_VALUE IS NULL OR m.PROPERTY_VALUE <= 0
            THEN 'INVALID_PROPERTY_VALUE'
        WHEN m.MONTHLY_INCOME IS NULL OR m.MONTHLY_INCOME <= 0
            THEN 'INVALID_MONTHLY_INCOME'
        WHEN c.CREDIT_SCORE IS NULL
            THEN 'MISSING_CREDIT_SCORE'
        WHEN c.MONTHLY_DEBT IS NULL OR c.MONTHLY_DEBT < 0
            THEN 'INVALID_MONTHLY_DEBT'
        ELSE NULL
    END AS TECHNICAL_REJECTION_REASON

FROM {{ ref('stg_applications') }} m
FULL OUTER JOIN {{ ref('stg_credit_bureau') }} c
    ON m.APPLICANT_ID = c.APPLICANT_ID
