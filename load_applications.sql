
-- Load mortgage application JSON into Snowflake RAW.

-- Create an internal stage for the JSON file.
CREATE STAGE IF NOT EXISTS MORTGAGE_DB.RAW.MORTGAGE_JSON_STAGE
    FILE_FORMAT = MORTGAGE_DB.RAW.MORTGAGE_JSON_FORMAT;

-- After uploading the JSON file to the stage, load its records.
COPY INTO MORTGAGE_DB.RAW.MORTGAGE_APPLICATIONS_RAW
    (PAYLOAD, SOURCE_FILE)
FROM (
    SELECT
        $1,
        METADATA$FILENAME
    FROM @MORTGAGE_DB.RAW.MORTGAGE_JSON_STAGE
)
FILE_FORMAT = (FORMAT_NAME = 'MORTGAGE_DB.RAW.MORTGAGE_JSON_FORMAT')
ON_ERROR = 'ABORT_STATEMENT';
